def add(a: float, b: float) -> float:
    """加法运算"""
    return a + b
def multiply(a: float, b: float) -> float:
    """乘法运算"""
    return a * b
if __name__ == "__main__":
    print(f"2 + 3 = {add(2, 3)}")
    print(f"4 * 5 = {multiply(4, 5)}")
def power(a: float, b: float) -> float: 
    """乘方运算""" 
    return a ** b
